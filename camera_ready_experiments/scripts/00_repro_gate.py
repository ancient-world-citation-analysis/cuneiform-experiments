"""Reproduction gate: rebuild the corpora with the released pipeline and
re-run the paper's full-corpus Morfessor transfer matrix (Table 3, Morfessor
panel). Every rebuttal experiment is only trustworthy if this matches
outputs/table3_morfessor_transfer.json.

Note on tolerance: morfessor.BaselineModel.train_batch() shuffles compound
order with the global `random` module each epoch, so training is not
bit-reproducible across differing RNG call histories. The paper's own Table 3
caption bounds document-bootstrap CIs at +/-0.006; we gate at that tolerance.
"""
import json
import os
import random
import time

import numpy as np

import common
from common import (LANGS, get_corpora, lang_docs, train_morfessor,
                    evaluate_morfessor, vocab_overlap)

TOL = 0.006

t0 = time.time()
cache = get_corpora()
documents = cache["documents"]
print(f"[{time.time()-t0:7.1f}s] corpora ready")

docs = {lang: lang_docs(documents, lang) for lang in LANGS}
for lang in LANGS:
    toks = sum(len(d.split()) for d in docs[lang])
    print(f"  {lang.upper()}: {len(docs[lang]):>6d} docs | {toks:>10,d} split-tokens")

# Published numbers (generated by the released notebooks; matches Table 3)
ref_path = os.path.join(common.REPO, "outputs", "table3_morfessor_transfer.json")
with open(ref_path) as f:
    ref = json.load(f)["morfessor_transfer"]

expected_docs = {"akk": 13502, "sux": 394, "elx": 84}
for lang, n in expected_docs.items():
    status = "OK" if len(docs[lang]) == n else "MISMATCH"
    print(f"  doc-count gate {lang}: got {len(docs[lang])}, expected {n} -> {status}")

models, vocabs = {}, {}
for lang in LANGS:
    random.seed(42)  # mirrors notebook set_seeds(42); morfessor shuffles internally
    t = time.time()
    models[lang], vocabs[lang] = train_morfessor(docs[lang])
    print(f"[{time.time()-t:7.1f}s] trained Morfessor on full {lang.upper()} "
          f"({len(vocabs[lang])} types)")

results = {}
all_ok = True
for src in LANGS:
    for tgt in LANGS:
        if src == tgt:
            continue
        t = time.time()
        m = evaluate_morfessor(models[src], docs[tgt])
        m["vocab_overlap"] = vocab_overlap(vocabs[src], docs[tgt])
        key = f"{src}->{tgt}"
        results[key] = m
        ref_f1 = ref[key]["f1"]
        delta = m["f1"] - ref_f1
        ok = abs(delta) <= TOL
        all_ok &= ok
        print(f"[{time.time()-t:7.1f}s] {key}: F1={m['f1']:.4f} "
              f"(published {ref_f1:.4f}, delta {delta:+.4f}) "
              f"{'OK' if ok else '** OUT OF TOLERANCE **'}")

out = {
    "gate_tolerance": TOL,
    "all_within_tolerance": bool(all_ok),
    "doc_counts": {l: len(docs[l]) for l in LANGS},
    "split_token_counts": {l: int(sum(len(d.split()) for d in docs[l])) for l in LANGS},
    "vocab_sizes": {l: len(vocabs[l]) for l in LANGS},
    "reproduced_transfer": results,
    "published_reference": {k: {"f1": v["f1"]} for k, v in ref.items()},
}
gate_path = os.path.join(common.CACHE_DIR, "full_transfer_repro.json")
with open(gate_path, "w") as f:
    json.dump(out, f, indent=2)
print(f"\n[saved] {gate_path}")
print(f"GATE {'PASSED' if all_ok else 'FAILED'} (tolerance +/-{TOL})")
print(f"total {time.time()-t0:.1f}s")
